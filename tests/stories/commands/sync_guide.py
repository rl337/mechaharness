"""Generate docs/guides/user-stories.md from suite stage YAML prose."""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

from pyiv.command import CLICommand

from tests.stories.catalog import (
    FIXTURES_ROOT,
    collect_canonical_stories,
    validate_story_fixtures,
)
from tests.stories.suite_catalog import suite_meta_for_guide, validate_suite_fixtures

GUIDE_PATH = (
    Path(__file__).resolve().parents[3] / "docs" / "guides" / "user-stories.md"
)
PERSONAS_PATH = FIXTURES_ROOT / "personas.json"
PERSONA_ORDER = ("nubble", "fangore", "taloneth")


def _render_footnotes(story: dict[str, Any]) -> list[str]:
    footnotes = story.get("footnotes") or []
    if not footnotes:
        return []
    lines = ["#### Footnotes", ""]
    narrative = str(story.get("narrative") or "")
    cited = set(re.findall(r"\[\^([A-Za-z0-9_-]+)\]", narrative))
    for i, item in enumerate(footnotes, start=1):
        fid = str(item["id"])
        label = str(item["label"])
        url = str(item["url"])
        note = item.get("note")
        suffix = f" — {note}" if isinstance(note, str) and note.strip() else ""
        if cited:
            lines.append(f"[^{fid}]: [{label}]({url}){suffix}")
        else:
            lines.append(f"{i}. [{label}]({url}){suffix}")
    lines.append("")
    return lines


def render_guide(stories: dict[str, dict[str, Any]], personas: dict[str, Any]) -> str:
    lines: list[str] = [
        "<!-- Generated by python -m tests.stories.commands sync-guide — do not edit by hand. -->",
        "",
        "# User stories",
        "",
        str(personas["intro"]).rstrip(),
        "",
        "## Personas",
        "",
    ]
    persona_meta = {p["id"]: p for p in personas["personas"]}
    for pid in PERSONA_ORDER:
        p = persona_meta[pid]
        lines.append(f"### {p['name']} — {p['role']}")
        lines.append("")
        lines.append(str(p["bio"]).rstrip())
        lines.append("")

    lines.append("## Running the suite")
    lines.append("")
    lines.append(str(personas["running_suite"]).rstrip())
    lines.append("")
    lines.append("## Models")
    lines.append("")
    lines.append(str(personas["models"]).rstrip())
    lines.append("")

    lines.append("## Suites")
    lines.append("")
    suites_blurb = personas.get("suites")
    if isinstance(suites_blurb, str) and suites_blurb.strip():
        lines.append(suites_blurb.rstrip())
        lines.append("")
    for suite in suite_meta_for_guide():
        mode = suite["mode"]
        ordered = " (ordered)" if suite.get("ordered") else ""
        lines.append(f"### `{suite['id']}` — {suite['title']}")
        lines.append("")
        lines.append(
            f"Persona **{suite['persona']}**; execution `{mode}`{ordered}; "
            f"{suite['stage_count']} stage(s)."
        )
        lines.append("")
        story_list = ", ".join(f"`{s}`" for s in suite["stories"])
        lines.append(f"Stories: {story_list}")
        lines.append("")

    by_persona: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for story in stories.values():
        by_persona[str(story["persona"])].append(story)

    for pid in PERSONA_ORDER:
        name = persona_meta[pid]["name"]
        lines.append(f"## {name}'s stories")
        lines.append("")
        for story in sorted(by_persona.get(pid, []), key=lambda s: s["id"]):
            lines.append(f"### `{story['id']}` — {story['title']}")
            lines.append("")
            lines.append(str(story["narrative"]).rstrip())
            lines.append("")
            lines.append("#### Implementation")
            lines.append("")
            lines.append(str(story["implementation"]).rstrip())
            lines.append("")
            lines.append("#### Validation")
            lines.append("")
            lines.append(str(story["validation"]).rstrip())
            lines.append("")
            lines.extend(_render_footnotes(story))

    return "\n".join(lines).rstrip() + "\n"


class SyncGuideCommand(CLICommand):
    """Write or check docs/guides/user-stories.md from stage YAML prose."""

    @classmethod
    def get_name(cls) -> str:
        return "sync-guide"

    @classmethod
    def get_description(cls) -> str:
        return "Generate docs/guides/user-stories.md from suite stage YAML prose."

    @classmethod
    def add_args(cls, parser: argparse.ArgumentParser) -> None:
        parser.add_argument(
            "--check",
            action="store_true",
            help="exit 1 if the guide is missing or differs from fixtures",
        )

    def run(self) -> None:
        errors = validate_story_fixtures()
        if errors:
            print("story validation failed:", file=sys.stderr)
            for err in errors:
                print(f"  {err}", file=sys.stderr)
            self._exit_code = 1
            return
        suite_errors = validate_suite_fixtures(require_full_static_coverage=True)
        if suite_errors:
            print("suite validation failed:", file=sys.stderr)
            for err in suite_errors:
                print(f"  {err}", file=sys.stderr)
            self._exit_code = 1
            return
        if not PERSONAS_PATH.is_file():
            print(f"missing {PERSONAS_PATH}", file=sys.stderr)
            self._exit_code = 1
            return

        personas = json.loads(PERSONAS_PATH.read_text(encoding="utf-8"))
        stories = collect_canonical_stories()
        rendered = render_guide(stories, personas)

        if self.args.check:
            if not GUIDE_PATH.is_file():
                print(f"missing generated guide {GUIDE_PATH}", file=sys.stderr)
                self._exit_code = 1
                return
            if GUIDE_PATH.read_text(encoding="utf-8") != rendered:
                print(
                    f"{GUIDE_PATH} is out of date; run "
                    "python -m tests.stories.commands sync-guide",
                    file=sys.stderr,
                )
                self._exit_code = 1
                return
            print(f"ok: {GUIDE_PATH} matches fixtures ({len(stories)} stories)")
            self._exit_code = 0
            return

        GUIDE_PATH.parent.mkdir(parents=True, exist_ok=True)
        GUIDE_PATH.write_text(rendered, encoding="utf-8")
        print(f"wrote {GUIDE_PATH} ({len(stories)} stories)")
        self._exit_code = 0
